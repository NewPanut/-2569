// Function to parse the user's P.1 CSV and transform into StudentRecord (No additional subjects for P.1-3)
export function parseP1Students(): StudentRecord[] {
  const lines = RAW_P1_CSV.split('\n').filter(l => l.trim().length > 0);
  const students: StudentRecord[] = [];

  // line 0 is header: เลขที่,เลขประจำตัวนักเรียน,ชื่อ-สกุล,ชั้น/ห้อง,การอ่านภาษาไทย,การอ่านภาษาอังกฤษ,การเขียนภาษาไทย,การเขียนภาษาอังกฤษ,การคิดคำนวณ,วิทยาศาสตร์สิ่งแวดล้อมและเทคโนโลยี,สังคมและความเป็นพลเมือง,เศรษฐกิจและการเงิน,สุขภาพกายและจิต,ศิลปะและวัฒนธรรมเพื่อสุนทรียภาพ,รวม
  for (let i = 1; i < lines.length; i++) {
    const cols = lines[i].split(',').map(c => c.trim());
    if (cols.length < 14) continue;

    const seatNo = parseInt(cols[0], 10) || i;
    const studentId = cols[1];
    const name = cols[2];
    const gradeLevel = cols[3];

    // Core 10 subject scores for Lower Primary (P.1-3) Curriculum 2568
    const subjectNames = [
      'การอ่านภาษาไทย',
      'การอ่านภาษาอังกฤษ',
      'การเขียนภาษาไทย',
      'การเขียนภาษาอังกฤษ',
      'การคิดคำนวณ',
      'วิทยาศาสตร์สิ่งแวดล้อมและเทคโนโลยี',
      'สังคมและความเป็นพลเมือง',
      'เศรษฐกิจและการเงิน',
      'สุขภาพกายและจิต',
      'ศิลปะและวัฒนธรรมเพื่อสุนทรียภาพ'
    ];

    const subjects: SubjectItem[] = subjectNames.map((subjName, idx) => {
      const score = parseFloat(cols[4 + idx]) || 0;
      const gradeInfo = getGradeInfo(score);
      return {
        id: `subj_${idx + 1}`,
        name: subjName,
        maxScore: 100,
        earnedScore: score,
        remarks: ''
      };
    });

    // P.1-3 has no additional subjects: Total corresponds exactly to the CSV "รวม"
    const totalScore = subjects.reduce((sum, s) => sum + s.earnedScore, 0);
    const maxPossibleScore = subjects.length * 100;
    const averagePercentage = Number(((totalScore / maxPossibleScore) * 100).toFixed(2));
    const overallGrade = getGradeInfo(averagePercentage);

    students.push({
      id: studentId,
      seatNo,
      name,
      gradeLevel,
      curriculum: 'p1_3',
      academicYear: '2569',
      subjects,
      totalScore,
      maxPossibleScore,
      averagePercentage,
      gpaText: overallGrade.grade,
      evaluationRemarks: overallGrade.remarks,
      readingAnalysisEvaluation: averagePercentage >= 80 ? 'ดีเยี่ยม' : averagePercentage >= 65 ? 'ดี' : 'ผ่าน',
      desiredCharacteristicsEvaluation: 'ดีเยี่ยม',
      activitiesEvaluation: 'ผ่าน',
      teacherRemarks: averagePercentage >= 85 
        ? 'มีความตั้งใจเรียนเป็นเลิศ มีความประพฤติเรียบร้อยและมีมนุษยสัมพันธ์ดีเยี่ยม'
        : averagePercentage >= 70
        ? 'มีความสนใจในการเรียนดี ส่งงานสม่ำเสมอ แนะนำให้พัฒนาทักษะการอ่านและคิดคำนวณเพิ่มเติม'
        : 'ควรฝึกทักษะการอ่านและการเขียนเพิ่มเติม และให้เวลากับการทบทวนบทเรียนสม่ำเสมอ'
    });
  }

  return students;
}

